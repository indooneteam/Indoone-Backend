"""Conversation history, on Postgres.

The SQLite tests run everywhere. These run only when a Postgres is pointed at, which
CI does with a service container. Without one the module skips, so a plain checkout
stays green.

What is checked is what could differ between the two databases: the schema builds with
an identity column instead of SQLite's AUTOINCREMENT, the messages keep their order,
ownership still refuses another user, a closed conversation is still closed, the purge
compares timestamps correctly, and the message cap still closes a conversation.
"""

from __future__ import annotations

import os
import uuid

import pytest

from app.storage import database

_POSTGRES_URL = os.getenv("INDOONE_TEST_DATABASE_URL", "").strip()


@pytest.fixture()
def store(monkeypatch: pytest.MonkeyPatch):
    """A conversation store pointed at Postgres."""

    if not _POSTGRES_URL:
        pytest.skip("set INDOONE_TEST_DATABASE_URL to run the Postgres conversation tests")
    monkeypatch.setenv("INDOONE_DATABASE_URL", _POSTGRES_URL)
    from app.ai.memory.conversation_store import ConversationStore

    return ConversationStore()


def _conversation() -> str:
    return f"conversation-{uuid.uuid4().hex[:12]}"


def test_it_is_actually_talking_to_postgres(store) -> None:
    assert database.dialect() == "postgres"
    assert database.identity_column().startswith("BIGINT GENERATED BY DEFAULT AS IDENTITY")


def test_messages_keep_their_order(store) -> None:
    conversation = _conversation()

    store.append(conversation, [("user", "first"), ("assistant", "second")], user_id="user-pg")
    store.append(conversation, [("user", "third")], user_id="user-pg")

    assert store.recent(conversation, user_id="user-pg") == [
        ("user", "first"),
        ("assistant", "second"),
        ("user", "third"),
    ]
    assert store.message_count(conversation, user_id="user-pg") == 3


def test_another_user_cannot_read_it(store) -> None:
    conversation = _conversation()
    store.append(conversation, [("user", "private")], user_id="user-one")

    with pytest.raises(PermissionError):
        store.recent(conversation, user_id="user-two")


def test_a_closed_conversation_refuses_new_messages(store) -> None:
    conversation = _conversation()
    store.append(conversation, [("user", "hello")], user_id="user-pg")
    store.close(conversation, user_id="user-pg")

    assert store.is_closed(conversation, user_id="user-pg") is True
    with pytest.raises(ValueError):
        store.append(conversation, [("user", "again")], user_id="user-pg")


def test_deleting_removes_the_messages_too(store) -> None:
    conversation = _conversation()
    store.append(conversation, [("user", "gone soon")], user_id="user-pg")

    store.delete(conversation, user_id="user-pg")

    with pytest.raises(ValueError):
        store.recent(conversation, user_id="user-pg")


def test_the_message_cap_closes_the_conversation(store, monkeypatch: pytest.MonkeyPatch) -> None:
    from app.ai.memory.conversation_store import ConversationStore

    capped = ConversationStore(max_messages=2)
    conversation = _conversation()

    capped.append(conversation, [("user", "one")], user_id="user-pg")
    capped.append(conversation, [("user", "two")], user_id="user-pg")

    assert capped.is_closed(conversation, user_id="user-pg") is True
    assert capped.recent(conversation, user_id="user-pg") == [("user", "one"), ("user", "two")]


def test_the_purge_removes_only_old_closed_conversations(store) -> None:
    old = _conversation()
    recent = _conversation()
    store.append(old, [("user", "old")], user_id="user-pg")
    store.append(recent, [("user", "recent")], user_id="user-pg")
    store.close(old, user_id="user-pg")
    store.close(recent, user_id="user-pg")
    # Age one of them past the cutoff, in the same text shape the store writes.
    with database.connect() as db:
        db.execute(
            "UPDATE conversations SET closed_at = ? WHERE conversation_id = ?",
            ("2000-01-01 00:00:00", old),
        )
        db.commit()

    removed = store.purge_expired_closed(max_age_days=7)

    assert removed >= 1
    with pytest.raises(ValueError):
        store.recent(old, user_id="user-pg")
    assert store.recent(recent, user_id="user-pg") == [("user", "recent")]


def test_listing_a_users_conversations_is_scoped(store) -> None:
    user = f"user-{uuid.uuid4().hex[:8]}"
    first = _conversation()
    second = _conversation()
    store.append(first, [("user", "a")], user_id=user)
    store.append(second, [("user", "b")], user_id=user)

    listed = store.list_for_user(user)

    assert {row["conversation_id"] for row in listed} == {first, second}
